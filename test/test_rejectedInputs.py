def buildEsM(variant):
    return fn.EnergySystemModel(
        locations={"loc1", "loc2"},
        commodities={"electricity", "hydrogen"},
        commodityUnitsDict={"electricity": "GW", "hydrogen": "GW"},
        numberOfTimeSteps=4,
        hoursPerTimeStep=2190,
        costUnit="1e9 Euro",
        lengthUnit="km",
        verboseLogLevel=2,
        **ESM_VARIANTS[variant],
    )


